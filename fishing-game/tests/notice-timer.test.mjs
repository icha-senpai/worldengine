import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createNoticeTimer } from '../apps/web/src/lib/game/notice-timer.ts';

test('notice lifetime, replacement, replay, dismissal, pause and reset', t => {
  t.mock.timers.enable({ apis: ['setTimeout'] });
  const changes = [];
  const timer = createNoticeTimer(visible => changes.push(visible));
  timer.show('one');
  t.mock.timers.tick(5999);
  assert.deepEqual(changes, [true]);
  timer.show('one');
  t.mock.timers.tick(1);
  assert.deepEqual(changes, [true, false]);
  timer.show('one');
  assert.deepEqual(changes, [true, false]);
  timer.show('two');
  t.mock.timers.tick(4000);
  timer.show('three');
  t.mock.timers.tick(2000);
  assert.deepEqual(changes, [true, false, true]);
  t.mock.timers.tick(3999);
  assert.deepEqual(changes, [true, false, true]);
  t.mock.timers.tick(1);
  assert.deepEqual(changes, [true, false, true, false]);
  timer.show('four');
  timer.dismiss();
  timer.show('four');
  assert.deepEqual(changes, [true, false, true, false, true, false]);
  timer.show('five');
  t.mock.timers.tick(5000);
  timer.pause();
  t.mock.timers.tick(20000);
  assert.equal(changes.at(-1), true);
  timer.resume();
  t.mock.timers.tick(5999);
  assert.equal(changes.at(-1), true);
  t.mock.timers.tick(1);
  assert.equal(changes.at(-1), false);
  timer.reset();
  timer.show('five');
  assert.equal(changes.at(-1), true);
  timer.reset();
  const snapshot = [...changes];
  t.mock.timers.tick(60000);
  assert.deepEqual(changes, snapshot);
});

test('a stale timeout callback cannot hide a replacement notice', t => {
  const originalSet = globalThis.setTimeout;
  const originalClear = globalThis.clearTimeout;
  const callbacks = [];
  globalThis.setTimeout = callback => { callbacks.push(callback); return callbacks.length; };
  globalThis.clearTimeout = () => {};
  t.after(() => { globalThis.setTimeout = originalSet; globalThis.clearTimeout = originalClear; });
  const changes = [];
  const timer = createNoticeTimer(visible => changes.push(visible));
  timer.show('old');
  timer.show('new');
  callbacks[0]();
  assert.deepEqual(changes, [true]);
  callbacks[1]();
  assert.deepEqual(changes, [true, false]);
  timer.reset();
});

test('pause, dismissal and reset leave no scheduled notice timers', t => {
  const originalSet = globalThis.setTimeout, originalClear = globalThis.clearTimeout;
  const scheduled = new Map();
  let next = 0;
  globalThis.setTimeout = callback => { scheduled.set(++next, callback); return next; };
  globalThis.clearTimeout = id => { scheduled.delete(id); };
  t.after(() => { globalThis.setTimeout = originalSet; globalThis.clearTimeout = originalClear; });
  const timer = createNoticeTimer(() => {});
  timer.show('a');
  assert.equal(scheduled.size, 1);
  timer.pause();
  assert.equal(scheduled.size, 0);
  timer.resume();
  assert.equal(scheduled.size, 1);
  timer.dismiss();
  assert.equal(scheduled.size, 0);
  timer.show('b');
  assert.equal(scheduled.size, 1);
  timer.reset();
  assert.equal(scheduled.size, 0);
});
